/**
 * Returns tier configuration for any given Level (1 through 250+).
 * Guaranteed to return a valid tier without undefined.
 */
export function getTierForLevel(level: number): LevelTierConfig {
  const safeLevel = Math.max(1, isNaN(level) ? 1 : Math.floor(level));
  const found = TIERS.find((t) => safeLevel >= t.minLevel && safeLevel <= t.maxLevel);
  return found || TIERS[TIERS.length - 1];
}

/**
 * Returns tier index (0 to 49) for a given level.
 */
export function getTierIndex(level: number): number {
  return getTierForLevel(level).tierIndex;
}
